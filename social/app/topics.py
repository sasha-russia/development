def norm(text: str) -> str:
    return (text or "").lower().replace("ё", "е")


def _pattern(stems: list[str]) -> re.Pattern:
    # A stem must start a word: "ям" matches "ямы", not "прямо".
    return re.compile("|".join(r"(?<![а-яa-z])" + re.escape(s) for s in stems))


TOPIC_PATTERNS = {topic: _pattern(stems) for topic, stems in TOPIC_KEYWORDS.items()}
NEGATIVE_PATTERN = _pattern(NEGATIVE_WORDS)
POSITIVE_PATTERN = _pattern(POSITIVE_WORDS)
ADMIN_PATTERN = _pattern(ADMIN_WORDS)
LOCAL_PATTERN = _pattern(LOCAL_KEYWORDS)


def mentions_local(text: str, extra: list[str] | None = None) -> bool:
    """About the city of Mytishchi, any settlement of the district or a known local object?"""
    from .localities import mentions_district

    t = norm(text)
    if mentions_district(t) or LOCAL_PATTERN.search(t):
        return True
    return bool(extra) and _pattern(extra).search(t) is not None
