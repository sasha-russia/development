# Parts of the city people name instead of "Мытищи".
CITY_PARTS = ["Перловка", "Тайнинка", "Тайнинская", "Новые Мытищи", "Леонидовка", "Шараповка",
              "Строитель (Мытищи)", "Дружба (Мытищи)", "Яуза"]

NAMES = sorted({name for name, _ in SETTLEMENTS})


def _stem(name: str) -> str:
    """Drop the case ending so "Пирогово" also matches "Пирогове", "Жостово" — "Жостова"."""
    n = norm(name).replace("«", "").replace("»", "")
    for ending in ("ское", "ская", "ое", "ая", "ий", "о", "а", "и", "ы", "е"):
        if n.endswith(ending) and len(n) - len(ending) >= 4:
            return n[: -len(ending)]
    return n


_TYPE_WORDS = r"(?:д\.|дер\.|деревн\w*|пос\.|п\.|поселк\w*|пгт|село|селе|с\.|снт|кп)\s*"
_DISTINCT = sorted({_stem(n) for n in NAMES if n not in AMBIGUOUS and n != "Мытищи"}, key=len, reverse=True)
_AMBIG = sorted({_stem(n) for n in AMBIGUOUS}, key=len, reverse=True)
DISTINCT_PATTERN = re.compile(r"(?<![а-я])(?:" + "|".join(map(re.escape, _DISTINCT)) + ")")
AMBIGUOUS_PATTERN = re.compile(_TYPE_WORDS + r"(?:" + "|".join(map(re.escape, _AMBIG)) + ")")
CITY_PATTERN = re.compile(r"(?<![а-я])(?:мытищ|перловк|тайнинк|новые мытищ|новых мытищ|леонидовк|шараповк)")


def mentions_district(text: str) -> bool:
    """Is the text about the city of Mytishchi or any settlement of the district?"""
    t = norm(text)
    if CITY_PATTERN.search(t) or DISTINCT_PATTERN.search(t) or AMBIGUOUS_PATTERN.search(t):
        return True
    return False


def find_settlement(text: str) -> str:
    """The first district settlement (other than the city) named in the text, or ""."""
    t = norm(text)
    best = None
    for name in NAMES:
        if name == "Мытищи":
            continue
        stem = _stem(name)
        pattern = (_TYPE_WORDS if name in AMBIGUOUS else r"(?<![а-я])") + re.escape(stem)
        m = re.search(pattern, t)
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), name)
    return best[1] if best else ""
